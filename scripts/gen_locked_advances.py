#!/usr/bin/env python3
"""Generate locked-advance trigger, effect, and localization files from data/locked_advances.yaml.

Usage:
    conda run --no-capture-output -n eu5 python scripts/gen_locked_advances.py        # write files
    conda run --no-capture-output -n eu5 python scripts/gen_locked_advances.py --dry  # preview only

1对1原则: Each YAML field maps to one piece of output. The trigger_block field is
inserted verbatim; this generator is a template filler, not a code reasoner.

Generated files (DO NOT HAND-EDIT):
  src/in_game/common/scripted_triggers/tv_advance_lock_triggers.txt
  src/in_game/common/scripted_effects/tv_advance_unlock_effects.txt
  src/main_menu/localization/english/tv_advance_locks_l_english.yml
  src/main_menu/localization/simp_chinese/tv_advance_locks_l_simp_chinese.yml
"""
import sys
import argparse
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

try:
    import yaml
except ImportError:
    print("ERROR: PyYAML not installed. Run: conda install -n eu5 pyyaml", file=sys.stderr)
    sys.exit(1)

ROOT = Path(__file__).parent.parent
SRC = ROOT / "src"
DATA_YAML = ROOT / "data" / "locked_advances.yaml"

HEADER = "# AUTO-GENERATED by gen_locked_advances.py — DO NOT HAND-EDIT\n"

REQUIRED_FIELDS = ["id", "label_en", "label_zh", "research_unlock_var", "trigger_block", "loc"]
REQUIRED_LOC_FIELDS = ["en", "zh"]

# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

def indent(text: str, n: int = 1) -> str:
    """Prepend n tabs to every non-empty line."""
    prefix = "\t" * n
    lines = text.rstrip("\n").split("\n")
    return "\n".join(prefix + ln if ln.strip() else ln for ln in lines)


def write_file(path: Path, content: str, dry: bool) -> None:
    """Write UTF-8 BOM file, or print to stdout in dry mode."""
    if dry:
        print(f"\n{'='*72}")
        print(f"=== {path.relative_to(ROOT)}")
        print(f"{'='*72}")
        print(content[:2000])
        if len(content) > 2000:
            print(f"... [{len(content)-2000} more chars]")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8-sig")
        print(f"  wrote {path.relative_to(ROOT)}")


# ─────────────────────────────────────────────────────────────────────────────
# Validation
# ─────────────────────────────────────────────────────────────────────────────

def validate_yaml(entries: list) -> None:
    """Validate all required fields are present. Exits with error on failure."""
    errors = []
    for i, entry in enumerate(entries):
        entry_id = entry.get("id", f"<entry #{i}>")
        for field in REQUIRED_FIELDS:
            if field not in entry or entry[field] is None:
                errors.append(f"  Entry '{entry_id}': missing required field '{field}'")
        if "loc" in entry and entry["loc"] is not None:
            for lf in REQUIRED_LOC_FIELDS:
                if lf not in entry["loc"] or entry["loc"][lf] is None:
                    errors.append(f"  Entry '{entry_id}': missing required loc.{lf}")
        elif "loc" not in errors:  # already reported loc missing above
            pass
    if errors:
        print("ERROR: locked_advances.yaml validation failed:", file=sys.stderr)
        for e in errors:
            print(e, file=sys.stderr)
        sys.exit(1)


# ─────────────────────────────────────────────────────────────────────────────
# 1. TRIGGERS
# ─────────────────────────────────────────────────────────────────────────────

def gen_triggers(entries: list) -> str:
    lines = [HEADER, ""]
    lines.append(f"# {'─'*70}")
    lines.append("# ADVANCE LOCK TRIGGERS")
    lines.append(f"# {'─'*70}")
    lines.append("")
    for e in entries:
        aid = e["id"]
        lines.append(f"tv_advance_{aid}_is_locked = {{")
        lines.append(indent(e["trigger_block"].rstrip()))
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


# ─────────────────────────────────────────────────────────────────────────────
# 2. EFFECTS
# ─────────────────────────────────────────────────────────────────────────────

def gen_effects(entries: list) -> str:
    lines = [HEADER, ""]
    lines.append(f"# {'─'*70}")
    lines.append("# ADVANCE UNLOCK EFFECTS")
    lines.append(f"# {'─'*70}")
    lines.append("")
    for e in entries:
        aid = e["id"]
        AID = aid.upper()
        var = e["research_unlock_var"]
        lines.append(f"tv_unlock_advance_{aid}_effect = {{")
        lines.append(f"\tset_variable = {{ name = {var} value = 1 }}")
        lines.append(f"\tcustom_tooltip = TV_ADVANCE_UNLOCK_{AID}_TT")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


# ─────────────────────────────────────────────────────────────────────────────
# 3. LOCALIZATION
# ─────────────────────────────────────────────────────────────────────────────

def gen_localization(entries: list) -> tuple[str, str]:
    en_lines = ["l_english:", " # ── Advance Lock / Unlock Localization ─────────────────────────────────────"]
    zh_lines = ["l_simp_chinese:", " # ── 革新锁定/解锁 本地化 ────────────────────────────────────────────────────────"]

    for e in entries:
        aid = e["id"]
        AID = aid.upper()
        label_en = e["label_en"]
        label_zh = e["label_zh"]
        lock_en = e["loc"]["en"]
        lock_zh = e["loc"]["zh"]

        en_lines.append(f' TV_ADVANCE_NAME_{AID}:0 "{label_en}"')
        en_lines.append(f' TV_ADVANCE_LOCK_{AID}_REASON:0 "{lock_en}"')
        en_lines.append(f' TV_ADVANCE_UNLOCK_{AID}_TT:0 "{label_en} has been unlocked through Academy research."')

        zh_lines.append(f' TV_ADVANCE_NAME_{AID}:0 "{label_zh}"')
        zh_lines.append(f' TV_ADVANCE_LOCK_{AID}_REASON:0 "{lock_zh}"')
        zh_lines.append(f' TV_ADVANCE_UNLOCK_{AID}_TT:0 "{label_zh}已通过科学院研究解锁。"')

    return "\n".join(en_lines) + "\n", "\n".join(zh_lines) + "\n"


# ─────────────────────────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(description="Generate locked-advance mod files.")
    parser.add_argument("--dry", action="store_true", help="Print output to stdout; do not write files.")
    args = parser.parse_args()

    if not DATA_YAML.exists():
        print(f"ERROR: {DATA_YAML} not found", file=sys.stderr)
        sys.exit(1)

    with DATA_YAML.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh)

    entries = data.get("locked_advances", [])
    if not entries:
        print("ERROR: locked_advances list is empty", file=sys.stderr)
        sys.exit(1)

    # Validate before touching any files
    validate_yaml(entries)

    triggers_content = gen_triggers(entries)
    effects_content = gen_effects(entries)
    en_content, zh_content = gen_localization(entries)

    write_file(
        SRC / "in_game/common/scripted_triggers/tv_advance_lock_triggers.txt",
        triggers_content,
        args.dry,
    )
    write_file(
        SRC / "in_game/common/scripted_effects/tv_advance_unlock_effects.txt",
        effects_content,
        args.dry,
    )
    write_file(
        SRC / "main_menu/localization/english/tv_advance_locks_l_english.yml",
        en_content,
        args.dry,
    )
    write_file(
        SRC / "main_menu/localization/simp_chinese/tv_advance_locks_l_simp_chinese.yml",
        zh_content,
        args.dry,
    )

    if not args.dry:
        print("Done.")


if __name__ == "__main__":
    main()
