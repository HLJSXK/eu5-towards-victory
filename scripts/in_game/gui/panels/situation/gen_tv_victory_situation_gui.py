def emit(lines: list[str], level: int = 0, text: str = "") -> None:
    lines.append(f"{T * level}{text}" if text else "")


def fp(value: int) -> str:
    return f"(CFixedPoint){value}.0"


def player_var(name: str) -> str:
    return f"Country.MakeScope.GetVariable('{name}')"


def situation_var(name: str) -> str:
    return f"SituationView.GetActiveSituation.GetSituation.MakeScope.GetVariable('{name}')"


def selected_expr(path: dict) -> str:
    var = player_var("tv_victory_selected_path")
    order = int(path["gui"]["order"])
    eq = f"EqualTo_CFixedPoint({var}.GetValue, '{fp(order)}')"
    if order == 0:
        return f"Or(Not({var}.IsSet), {eq})"
    return f"And({var}.IsSet, {eq})"


def milestone_reached_expr(pid: str, n: int) -> str:
    var = player_var(f"tv_{pid}_milestone")
    return f"And({var}.IsSet, GreaterThanOrEqualTo_CFixedPoint({var}.GetValue, '{fp(n)}'))"


def reward_active_expr(pid: str, n: int, choice: int) -> str:
    var = player_var(f"tv_{pid}_m{n}_reward_choice")
    return f"And({var}.IsSet, EqualTo_CFixedPoint({var}.GetValue, '{fp(choice)}'))"


def reward_modifier_id(pid: str, n: int, choice: int) -> str:
    return f"tv_{pid}_m{n}_reward_{choice}_bonus"


def reward_icon_path(pid: str, n: int, choice: int) -> str:
    return f"{VICTORY_REWARD_ICON_DIR}/tv_victory_{pid}_m{n}_reward_{choice}.dds"


def milestone_label_key(n: int) -> str:
    if n == 3:
        return "TV_MILESTONE_V1_LABEL"
    if n == 5:
        return "TV_MILESTONE_V2_LABEL"
    return f"TV_MILESTONE_{n}_LABEL"


def score_loc_key(pid: str) -> str:
    return f"TV_S3_{pid.upper()}_SCORE"


