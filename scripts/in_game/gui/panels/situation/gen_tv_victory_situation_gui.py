def generate(data: dict) -> str:
    paths = sorted(data["paths"], key=lambda path: int(path["gui"]["order"]))
    lines = [HEADER.rstrip(), ""]
    append_tooltips(lines, paths)
    append_panel(lines, paths)
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry", action="store_true", help="Print to stdout instead of writing")
    args = parser.parse_args()

    with DATA_FILE.open(encoding="utf-8-sig") as file:
        data = yaml.safe_load(file)

    content = generate(data)
    if args.dry:
        print(content)
    else:
        OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
        OUT_FILE.write_text(content, encoding="utf-8-sig")
        print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
