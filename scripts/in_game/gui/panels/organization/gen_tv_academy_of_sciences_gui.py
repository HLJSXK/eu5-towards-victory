def gen_target_entry(advance: dict) -> str:
    gui_value = advance["gui_value"]
    loc_key = f"TV_RM_TARGET_{advance['id'].upper()}"
    float_str = f"{gui_value}.0"
    return (
        T*5 + "text_single = {\n"
        + T*6 + f"visible = \"[EqualTo_CFixedPoint(Country.MakeScope.GetVariable('tv_research_target').GetValue, '(CFixedPoint){float_str}')]\"\n"
        + T*6 + f"text = \"{loc_key}\"\n"
        + T*6 + "align = nobaseline\n"
        + T*5 + "}"
    )


def generate(data: dict) -> str:
    advances = data["locked_advances"]
    entries = "\n".join(gen_target_entry(a) for a in advances)
    return GUI_PREFIX + entries + "\n" + GUI_SUFFIX


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry", action="store_true", help="Print to stdout instead of writing")
    args = parser.parse_args()

    with open(DATA_FILE, encoding="utf-8") as f:
        data = yaml.safe_load(f)

    content = generate(data)

    if args.dry:
        print(content)
    else:
        OUT_FILE.write_text(content, encoding="utf-8-sig")
        print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
