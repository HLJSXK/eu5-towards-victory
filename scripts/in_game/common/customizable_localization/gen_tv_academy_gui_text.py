"""
Generate Academy of Sciences GUI text customizable_localization blocks.

Picks the current philosophy name and current debate-node line text by
variable value, replacing what used to be duplicated per-value GUI text
widgets in gen_tv_academy_of_sciences_gui.py. The (value, loc_key) pairs are
imported from that generator so there is a single source of truth.
"""

import sys
import argparse
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO_ROOT))

from scripts.in_game.gui.panels.organization.gen_tv_academy_of_sciences_gui import (
    PHILOSOPHY_ISSUES,
    CURRENT_NODE_LINE_KEYS,
)

OUT_FILE = (
    REPO_ROOT
    / "src"
    / "in_game"
    / "common"
    / "customizable_localization"
    / "tv_academy_gui_text.txt"
)

HEADER = """\
# @Generated by scripts/in_game/common/customizable_localization/gen_tv_academy_gui_text.py
#   Data:    scripts/in_game/gui/panels/organization/gen_tv_academy_of_sciences_gui.py (PHILOSOPHY_ISSUES, CURRENT_NODE_LINE_KEYS)
#   Regen:   conda run --no-capture-output -n eu5 python scripts/in_game/common/customizable_localization/gen_tv_academy_gui_text.py
# Do not edit directly - modify the source constants and re-run the generator.
"""


def _block(name: str, var_name: str, entries: list[tuple[int, str]]) -> str:
    lines = [f"{name} = {{", "\ttype = country", ""]
    for value, loc_key in entries:
        lines.append("\ttext = {")
        lines.append(f"\t\ttrigger = {{ var:{var_name} ?= {value} }}")
        lines.append(f"\t\tlocalization_key = {loc_key}")
        lines.append("\t}")
    lines.append("}")
    return "\n".join(lines)


def generate() -> str:
    blocks = [
        _block("tv_academy_philosophy_current_name", "tv_academy_philosophy_current", PHILOSOPHY_ISSUES),
        _block("tv_academy_debate_current_node_line", "tv_academy_debate_current_node_type", CURRENT_NODE_LINE_KEYS),
    ]
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry", action="store_true", help="Print to stdout instead of writing")
    args = parser.parse_args()

    content = generate()

    if args.dry:
        print(content)
    else:
        OUT_FILE.write_text(content, encoding="utf-8-sig")
        print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
