def sync_module_building_to_unit_gap(
    wonder: dict,
    part_key: str,
    building: str,
    indent: int,
) -> list[str]:
    del wonder
    unit_var = f"tv_wonder_{part_key}_units"
    return sync_building_from_target_levels(
        building,
        lambda target_level, target_indent: unit_gap_matches(unit_var, target_level, target_indent),
        indent,
    )


def combine_modules_to_helper_once(
    wonder: dict,
    parts: list[dict],
    indent: int,
) -> list[str]:
    helper = f"tv_wonder_{wonder['key']}"
    module_names = [f"tv_wonder_{wonder['key']}_{part['key']}" for part in parts]
    prefix = T * indent
    lines: list[str] = []
    for idx, level in enumerate(range(6, 0, -1)):
        head = "if" if idx == 0 else "else_if"
        lines.append(f"{prefix}{head} = {{")
        lines.append(f"{prefix}{T}limit = {{")
        for module in module_names:
            lines.append(f"{prefix}{T}{T}{loc_level(module, '>=', level)}")
        lines.append(f"{prefix}{T}}}")
        lines.append(f"{prefix}{T}if = {{")
        lines.append(f"{prefix}{T}{T}limit = {{ has_building = {building_type_ref(helper)} }}")
        lines.extend(
            [
                f"{prefix}{T}{line}"
                for line in change_level(helper, level)
            ]
        )
        lines.append(f"{prefix}{T}}}")
        lines.append(f"{prefix}{T}else = {{")
        lines.append(
            f'{prefix}{T}{T}construct_building = {{ building_type = {building_type_ref(helper)} cost_multiplier = 0 cost_multiplier_reason = "game_concept_event" instant = yes }}'
        )
        if level > 1:
            lines.extend(
                [
                    f"{prefix}{T}{line}"
                    for line in change_level(helper, level - 1)
                ]
            )
        lines.append(f"{prefix}{T}}}")
        for module in module_names:
            lines.extend(
                [
                    f"{prefix}{T}{line}"
                    for line in change_level(module, -level)
                ]
            )
        lines.append(f"{prefix}}}")
    return lines


def append_clear_current_base_modifiers_effect(lines: list[str], name: str, wonders: list[dict]) -> None:
    lines.append(f"{name} = {{")
    for idx, wonder in enumerate(wonders):
        head = "if" if idx == 0 else "else_if"
        lines.append(f"{T}{head} = {{")
        lines.append(f"{T}{T}limit = {{ var:tv_wonder_locked ?= {wonder['id']} }}")
        for level in range(1, 7):
            lines.append(f"{T}{T}remove_country_modifier = tv_wonder_{wonder['key']}_level_{level}")
        lines.append(f"{T}}}")
    lines.append("}")
    lines.append("")


def append_clear_current_ceremony_modifiers_effect(lines: list[str], name: str, wonders: list[dict], mechanics: dict) -> None:
    lines.append(f"{name} = {{")
    for idx, wonder in enumerate(wonders):
        head = "if" if idx == 0 else "else_if"
        lines.append(f"{T}{head} = {{")
        lines.append(f"{T}{T}limit = {{ var:tv_wonder_locked ?= {wonder['id']} }}")
        for building in wonder["final_buildings"].values():
            ceremony_modifier = ceremony_modifier_for_building(wonder, mechanics, building)
            if ceremony_modifier is None:
                continue
            modifier_name, _ = ceremony_modifier
            lines.append(f"{T}{T}remove_country_modifier = {modifier_name}")
        lines.append(f"{T}}}")
    lines.append("}")
    lines.append("")


def append_destroy_intermediate_buildings_at_location_effect(
    lines: list[str],
    name: str,
    wonders: list[dict],
    parts: list[dict],
) -> None:
    lines.append(f"{name} = {{")
    lines.append(f"{T}prev = {{ save_scope_as = tv_wonder_module_owner }}")
    for wonder in wonders:
        helper = f"tv_wonder_{wonder['key']}"
        module_names = [f"tv_wonder_{wonder['key']}_{part['key']}" for part in parts]
        final_names = list(wonder["final_buildings"].values())
        lines.append(f"{T}if = {{")
        lines.append(f"{T}{T}limit = {{")
        lines.extend(any_building_block(final_names, 3))
        lines.append(f"{T}{T}}}")
        for building in [helper, *module_names]:
            lines.append(f"{T}{T}if = {{")
            lines.append(f"{T}{T}{T}limit = {{ has_building = building_type:{building} }}")
            lines.append(f"{T}{T}{T}destroy_building_forcefully = \"building(building_type:{building}|scope:tv_wonder_module_owner)\"")
            lines.append(f"{T}{T}}}")
        lines.append(f"{T}}}")
    lines.append("}")
    lines.append("")


