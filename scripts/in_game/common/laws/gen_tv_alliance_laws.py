"""
Generate src/in_game/common/laws/tv_alliance_laws.txt from data/alliance_laws.yaml.

Pattern: 5 law categories × 4 policy levels each.
- L1 is a minimal stub (no allow, no on_activate, no country_modifier).
- L2-L4 share identical boilerplate; only cohesion_cost, country_modifier, and policy IDs differ.
- wants_this_policy_bias add values are fixed: L2=30, L3=20, L4=10.
"""

import sys
import argparse
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import yaml

REPO_ROOT = Path(__file__).resolve().parents[4]
DATA_FILE = REPO_ROOT / "data" / "alliance_laws.yaml"
OUT_FILE = REPO_ROOT / "src" / "in_game" / "common" / "laws" / "tv_alliance_laws.txt"

T = "\t"

FILE_HEADER = (
    "# @Generated by scripts/in_game/common/laws/gen_tv_alliance_laws.py\n"
    "#   Data:    data/alliance_laws.yaml\n"
    "#   Regen:   conda run --no-capture-output -n eu5 python scripts/in_game/common/laws/gen_tv_alliance_laws.py\n"
    "# Do not edit directly — modify the data file and re-run the generator.\n"
    "#\n"
    "# ══════════════════════════════════════════════════════════════════════════════\n"
    "# TOWARDS VICTORY — DIPLOMATIC ALLIANCE LAWS\n"
    "# 5 law categories × 4 policy levels each\n"
    "# Cohesion thresholds: L1=0, L2=25, L3=50, L4=75\n"
    "# Each upgrade from L1 increments tv_alliance_tier by 1\n"
    "# ══════════════════════════════════════════════════════════════════════════════\n"
)

LAW_DIVIDER = "# ──────────────────────────────────────────────────────────────────────────────"


def _indent_block(text: str, depth: int) -> str:
    prefix = T * depth
    return "\n".join(prefix + line if line.strip() else "" for line in text.rstrip().splitlines())


def gen_l1(policy: dict) -> str:
    pid = policy["id"]
    comment = policy.get("display_comment", "")
    lines = []
    if comment:
        lines.append(T + f"# {comment}")
    lines.append(T + f"{pid} = {{")
    lines.append(T*2 + "level = 1")
    lines.append(T*2 + "wants_propose_policy = {")
    lines.append(T*3 + "subtract = {")
    lines.append(T*4 + 'desc = "TV_ALREADY_HAVE_BETTER"')
    lines.append(T*4 + "value = 100")
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T*2 + "wants_this_policy_bias = {")
    lines.append(T*3 + "add = {")
    lines.append(T*4 + 'desc = "TV_DEFAULT_POLICY"')
    lines.append(T*4 + "value = 10")
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T*2 + "wants_keep_policy = {")
    lines.append(T*3 + "add = {")
    lines.append(T*4 + 'desc = "TV_STATUS_QUO"')
    lines.append(T*4 + "value = 20")
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T + "}")
    return "\n".join(lines)


def gen_lN(policy: dict, prev_policy_id: str) -> str:
    pid = policy["id"]
    level = policy["level"]
    cost = policy["cohesion_cost"]
    comment = policy.get("display_comment", "")
    modifier_lines = policy["country_modifier"].rstrip()
    on_activate_note = (policy.get("on_activate_note") or "").strip()
    bias_add = 30 - (level - 2) * 10  # 30/20/10 for levels 2/3/4

    lines = []
    if comment:
        lines.append(T + f"# {comment}")
    lines.append(T + f"{pid} = {{")
    lines.append(T*2 + f"level = {level}")
    lines.append(T*2 + "allow = {")
    lines.append(T*3 + f"international_organization_has_policy = policy:{prev_policy_id}")
    lines.append(T*3 + "custom_tooltip = {")
    lines.append(T*4 + "text = TV_HAS_ALLIANCE_COHESION_TT")
    lines.append(T*4 + "scope:recipient = { has_variable = tv_alliance_cohesion }")
    lines.append(T*3 + "}")
    lines.append(T*3 + "scope:recipient = {")
    lines.append(T*4 + f"var:tv_alliance_cohesion >= {cost}")
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T*2 + "on_activate = {")
    lines.append(T*3 + "scope:recipient = {")
    lines.append(T*4 + f"change_variable = {{ name = tv_alliance_cohesion add = -{cost} }}")
    lines.append(T*4 + "change_variable = { name = tv_alliance_tier add = 1 }")
    if on_activate_note:
        lines.append(T*4 + on_activate_note)
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T*2 + "country_modifier = {")
    lines.append(_indent_block(modifier_lines, 3))
    lines.append(T*2 + "}")
    lines.append(T*2 + "wants_propose_policy = {")
    lines.append(T*3 + "add = {")
    lines.append(T*4 + 'desc = "TV_COHESION_REQUIREMENT"')
    lines.append(T*4 + "value = 20")
    lines.append(T*3 + "}")
    lines.append(T*3 + "if = {")
    lines.append(T*4 + "limit = {")
    lines.append(T*5 + "scope:recipient = {")
    lines.append(T*6 + "OR = {")
    lines.append(T*7 + "custom_tooltip = {")
    lines.append(T*8 + "text = TV_HAS_VARIABLE_NOT_SET_TT")
    lines.append(T*8 + "NOT = { has_variable = tv_alliance_cohesion }")
    lines.append(T*7 + "}")
    lines.append(T*7 + f"var:tv_alliance_cohesion < {cost}")
    lines.append(T*6 + "}")
    lines.append(T*5 + "}")
    lines.append(T*4 + "}")
    lines.append(T*4 + "subtract = {")
    lines.append(T*5 + 'desc = "TV_INSUFFICIENT_COHESION"')
    lines.append(T*5 + "value = 1000")
    lines.append(T*4 + "}")
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T*2 + "wants_this_policy_bias = {")
    lines.append(T*3 + "add = {")
    lines.append(T*4 + 'desc = "TV_UPGRADE_DESIRE"')
    lines.append(T*4 + f"value = {bias_add}")
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T*2 + "wants_keep_policy = {")
    lines.append(T*3 + "add = {")
    lines.append(T*4 + 'desc = "TV_STATUS_QUO"')
    lines.append(T*4 + "value = 30")
    lines.append(T*3 + "}")
    lines.append(T*2 + "}")
    lines.append(T + "}")
    return "\n".join(lines)


def gen_law(law: dict) -> str:
    lid = law["id"]
    category = law["law_category"]
    display_comment = law.get("display_comment", "")
    policies = law["policies"]

    lines = []
    lines.append(LAW_DIVIDER)
    if display_comment:
        lines.append(f"# {display_comment}")
    lines.append(LAW_DIVIDER)
    lines.append(f"{lid} = {{")
    lines.append(T + "type = international_organization")
    lines.append(T + f"law_category = {category}")
    lines.append(T + "potential = {")
    lines.append(T*2 + "international_organization_type = international_organization_type:tv_diplomatic_alliance")
    lines.append(T + "}")
    lines.append(T + "allow = {")
    lines.append(T*2 + "always = yes")
    lines.append(T + "}")
    lines.append(T + "locked = {")
    lines.append(T + "}")
    lines.append(T + "has_levels = yes")
    lines.append(T + "custom_tags = { forbids_no_policy }")
    lines.append("")

    # Generate policy blocks
    for i, policy in enumerate(policies):
        if policy["level"] == 1:
            lines.append(gen_l1(policy))
        else:
            prev_id = policies[i - 1]["id"]
            lines.append(gen_lN(policy, prev_id))
        if i < len(policies) - 1:
            lines.append("")

    lines.append("}")
    return "\n".join(lines)


def generate(data: dict) -> str:
    parts = [FILE_HEADER]
    for law in data["laws"]:
        parts.append(gen_law(law))
        parts.append("")
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry", action="store_true", help="Print to stdout instead of writing")
    args = parser.parse_args()

    with open(DATA_FILE, encoding="utf-8") as f:
        data = yaml.safe_load(f)

    content = generate(data)

    if args.dry:
        print(content)
    else:
        OUT_FILE.write_text(content, encoding="utf-8-sig")
        print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
