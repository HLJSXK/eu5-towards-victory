"""
Generate src/in_game/common/generic_action_ai_lists/tv_trade_league_list.txt.

All Trade League generic actions must be explicitly listed to avoid engine
warnings, even when the AI is discouraged from using the generated controls.
"""

import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import yaml

REPO_ROOT = Path(__file__).resolve().parents[4]
DATA_FILE = REPO_ROOT / "data" / "trade_league_goods.yaml"
OUT_FILE = (
    REPO_ROOT
    / "src"
    / "in_game"
    / "common"
    / "generic_action_ai_lists"
    / "tv_trade_league_list.txt"
)

HEADER = """\
# @Generated by scripts/in_game/common/generic_action_ai_lists/gen_tv_trade_league_list.py
#   Data:    data/trade_league_goods.yaml
#   Regen:   conda run --no-capture-output -n eu5 python scripts/in_game/common/generic_action_ai_lists/gen_tv_trade_league_list.py
# Do not edit directly - modify the data file and re-run the generator.

"""

BASE_ACTIONS = [
    "tv_appoint_trade_leader",
    "tv_remove_trade_leader",
    "tv_change_trade_leader",
    "tv_expel_trade_league_member",
]

ACTION_PATTERNS = [
    "tv_trade_select_monopoly_good_{good}",
    "tv_trade_set_virtual_demand_{good}",
    "tv_trade_increase_virtual_demand_{good}",
    "tv_trade_decrease_virtual_demand_{good}",
    "tv_trade_cancel_virtual_demand_{good}",
    "tv_trade_set_virtual_supply_{good}",
    "tv_trade_increase_virtual_supply_{good}",
    "tv_trade_decrease_virtual_supply_{good}",
    "tv_trade_cancel_virtual_supply_{good}",
    "tv_trade_set_embargo_{good}",
    "tv_trade_cancel_embargo_{good}",
]


def action_names(data: dict) -> list[str]:
    goods = data["goods"]
    names = list(BASE_ACTIONS)
    names.extend(category["action"] for category in data["categories"])
    for good in goods:
        names.extend(pattern.format(good=good) for pattern in ACTION_PATTERNS)
    return names


def validate_categories(data: dict) -> None:
    goods = data["goods"]
    seen: dict[str, str] = {}
    for category in data["categories"]:
        if not category["goods"]:
            raise ValueError(f"Trade League monopoly category {category['id']} has no goods")
        for good in category["goods"]:
            if good in seen:
                raise ValueError(
                    f"Trade League monopoly good {good} is in both {seen[good]} and {category['id']}"
                )
            seen[good] = category["id"]
    missing = [good for good in goods if good not in seen]
    extra = [good for good in seen if good not in goods]
    if missing:
        raise ValueError(f"Trade League monopoly goods missing categories: {', '.join(missing)}")
    if extra:
        raise ValueError(f"Trade League monopoly categories list unknown goods: {', '.join(extra)}")


def generate(data: dict) -> str:
    validate_categories(data)
    actions = "\n".join(f"\t\t{action}" for action in action_names(data))
    return (
        HEADER
        + "tv_trade_league_list = {\n"
        + "\tpotential = {\n"
        + "\t\tany_international_organizations_member_of = {\n"
        + "\t\t\tinternational_organization_type = international_organization_type:tv_trade_league\n"
        + "\t\t\texists = leader_country\n"
        + "\t\t\tleader_country = root\n"
        + "\t\t}\n"
        + "\t}\n"
        + "\tactions = {\n"
        + actions
        + "\n\t}\n"
        + "}\n"
    )


def main() -> None:
    with DATA_FILE.open(encoding="utf-8") as file:
        data = yaml.safe_load(file)
    OUT_FILE.write_text(generate(data), encoding="utf-8-sig")
    print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
