"""
Generate src/in_game/common/generic_action_ai_lists/tv_trade_league_list.txt.

All Trade League generic actions must be explicitly listed to avoid engine
warnings, even when the AI is discouraged from using the generated controls.
"""

import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import yaml

REPO_ROOT = Path(__file__).resolve().parents[4]
DATA_FILE = REPO_ROOT / "data" / "trade_league_goods.yaml"
TRADE_CHAIN_FILE = REPO_ROOT / "data" / "trade_chain.yaml"
OUT_FILE = (
    REPO_ROOT
    / "src"
    / "in_game"
    / "common"
    / "generic_action_ai_lists"
    / "tv_trade_league_list.txt"
)

HEADER = """\
# @Generated by scripts/in_game/common/generic_action_ai_lists/gen_tv_trade_league_list.py
#   Data:    data/trade_league_goods.yaml + data/trade_chain.yaml
#   Regen:   conda run --no-capture-output -n eu5 python scripts/in_game/common/generic_action_ai_lists/gen_tv_trade_league_list.py
# Do not edit directly - modify the data file and re-run the generator.

"""

BASE_ACTIONS = [
    "tv_appoint_trade_leader",
    "tv_remove_trade_leader",
    "tv_change_trade_leader",
    "tv_expel_trade_league_member",
]

MONOPOLY_SLOT_COUNT = 2
INTELLIGENCE_ROW_COUNT = 10

FIXED_MONOPOLY_ACTIONS = [
    *(f"tv_trade_select_monopoly_slot_{slot}" for slot in range(1, MONOPOLY_SLOT_COUNT + 1)),
    "tv_trade_previous_intelligence_page",
    "tv_trade_next_intelligence_page",
    *(f"tv_trade_select_intelligence_row_{row}" for row in range(1, INTELLIGENCE_ROW_COUNT + 1)),
    "tv_trade_start_intelligence_network",
    "tv_trade_cancel_intelligence_network",
    "tv_trade_add_chain_node",
    "tv_trade_set_selected_virtual_demand",
    "tv_trade_increase_selected_virtual_demand",
    "tv_trade_decrease_selected_virtual_demand",
    "tv_trade_cancel_selected_virtual_demand",
    "tv_trade_set_selected_virtual_supply",
    "tv_trade_increase_selected_virtual_supply",
    "tv_trade_decrease_selected_virtual_supply",
    "tv_trade_cancel_selected_virtual_supply",
    "tv_trade_set_selected_embargo",
    "tv_trade_cancel_selected_embargo",
]


def action_names(data: dict) -> list[str]:
    names = list(BASE_ACTIONS)
    names.extend(FIXED_MONOPOLY_ACTIONS)
    return names


def generate(data: dict) -> str:
    actions = "\n".join(f"\t\t{action}" for action in action_names(data))
    return (
        HEADER
        + "tv_trade_league_list = {\n"
        + "\tpotential = {\n"
        + "\t\tany_international_organizations_member_of = {\n"
        + "\t\t\tinternational_organization_type = international_organization_type:tv_trade_league\n"
        + "\t\t\texists = leader_country\n"
        + "\t\t\tleader_country = root\n"
        + "\t\t}\n"
        + "\t}\n"
        + "\tactions = {\n"
        + actions
        + "\n\t}\n"
        + "}\n"
    )


def main() -> None:
    with DATA_FILE.open(encoding="utf-8") as file:
        data = yaml.safe_load(file)
    with TRADE_CHAIN_FILE.open(encoding="utf-8") as file:
        yaml.safe_load(file)
    OUT_FILE.write_text(generate(data), encoding="utf-8-sig")
    print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
