"""
Generate src/in_game/common/static_modifiers/tv_trade_chain_display_modifiers.txt.

These static modifiers are display-only GUI rows for Trade Chain strength.
Actual Trade Chain effects are applied by scripted effects and temporary demand.
"""

import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import yaml

REPO_ROOT = Path(__file__).resolve().parents[4]
DATA_FILE = REPO_ROOT / "data" / "trade_chain.yaml"
OUT_FILE = (
    REPO_ROOT
    / "src"
    / "in_game"
    / "common"
    / "static_modifiers"
    / "tv_trade_chain_display_modifiers.txt"
)

HEADER = """\
# @Generated by scripts/in_game/common/static_modifiers/gen_tv_trade_chain_display_modifiers.py
#   Data:    data/trade_chain.yaml
#   Regen:   conda run --no-capture-output -n eu5 python scripts/in_game/common/static_modifiers/gen_tv_trade_chain_display_modifiers.py
# Do not edit directly - modify the data file and re-run the generator.

"""


def format_value(value: float) -> str:
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return text if text else "0"


def modifier_block(strength: int, data: dict) -> str:
    bargaining = strength * float(data["bargaining_efficiency_per_strength"])
    medium = int(data["medium_strength_threshold"])
    strong = int(data["strong_strength_threshold"])
    lines = [
        f"tv_trade_chain_strength_display_{strength} = {{",
        f"\ttv_trade_bargaining_efficiency = {format_value(bargaining)}",
    ]
    if strength >= medium:
        lines.append("\tmerchant_maintenance_efficiency = 0.10")
    if strength >= strong:
        lines.append("\tglobal_merchant_power = 0.20")
    lines.append("}")
    return "\n".join(lines)


def generate(data: dict) -> str:
    cap = int(data["strength_display_cap"])
    blocks = (modifier_block(strength, data) for strength in range(cap + 1))
    return HEADER + "\n\n".join(blocks) + "\n"


def main() -> None:
    with DATA_FILE.open(encoding="utf-8") as file:
        data = yaml.safe_load(file)
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(generate(data), encoding="utf-8-sig")
    print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
