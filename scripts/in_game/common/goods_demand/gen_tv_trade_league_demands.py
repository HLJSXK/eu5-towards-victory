"""
Generate src/in_game/common/goods_demand/tv_trade_league_demands.txt.

Each tracked Trade League good needs a hidden demand entry so monopoly actions
can add scaled temporary demand to a selected market.
"""

import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import yaml

REPO_ROOT = Path(__file__).resolve().parents[4]
DATA_FILE = REPO_ROOT / "data" / "trade_league_goods.yaml"
OUT_FILE = (
    REPO_ROOT
    / "src"
    / "in_game"
    / "common"
    / "goods_demand"
    / "tv_trade_league_demands.txt"
)

HEADER = """\
# @Generated by scripts/in_game/common/goods_demand/gen_tv_trade_league_demands.py
#   Data:    data/trade_league_goods.yaml
#   Regen:   conda run --no-capture-output -n eu5 python scripts/in_game/common/goods_demand/gen_tv_trade_league_demands.py
# Do not edit directly - modify the data file and re-run the generator.

"""


def demand_block(good: str) -> str:
    return f"""\
tv_trade_virtual_demand_{good} = {{
\t{good} = 1
\thidden = yes
\tcategory = special_demands
}}
"""


def generate(data: dict) -> str:
    return HEADER + "\n".join(demand_block(good) for good in data["goods"])


def main() -> None:
    with DATA_FILE.open(encoding="utf-8") as file:
        data = yaml.safe_load(file)
    OUT_FILE.write_text(generate(data), encoding="utf-8-sig")
    print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
