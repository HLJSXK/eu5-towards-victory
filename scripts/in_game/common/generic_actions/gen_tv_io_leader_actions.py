def _io_title(io: dict) -> str:
    return io.get("display_name", io["id"].replace("_", " ").title())


def generate(data: dict, establishment: dict | None = None) -> str:
    parts = [HEADER]
    if establishment and establishment.get("paths"):
        leaders = _leader_by_id(data)
        parts.append(SECTION_BANNER.format(title="IO Establishment"))
        for est in sorted(establishment["paths"], key=lambda path: int(path.get("order", 0))):
            parts.append(gen_build_headquarters(est))
            parts.append(gen_establish_io(est, leaders[est["leader_id"]]))
            parts.append("")
    for io in data["ios"]:
        parts.append(SECTION_BANNER.format(title=_io_title(io)))
        parts.append(gen_appoint(io))
        parts.append(gen_remove(io))
        parts.append(gen_change(io))
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry", action="store_true", help="Print to stdout instead of writing")
    args = parser.parse_args()

    with open(DATA_FILE, encoding="utf-8") as f:
        data = yaml.safe_load(f)
    with open(ESTABLISHMENT_FILE, encoding="utf-8") as f:
        establishment = yaml.safe_load(f)

    content = generate(data, establishment)

    if args.dry:
        print(content)
    else:
        OUT_FILE.write_text(content, encoding="utf-8-sig")
        print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
