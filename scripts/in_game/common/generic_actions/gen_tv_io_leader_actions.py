"""
Generate src/in_game/common/generic_actions/tv_io_leader_actions.txt from data/io_leaders.yaml.

Pattern: 3 IOs × 3 actions (Appoint / Remove / Change) = 9 generic_action blocks.
Each block shares identical structural boilerplate; only the IO-specific strings differ.
"""

import sys
import argparse
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import yaml

REPO_ROOT = Path(__file__).resolve().parents[4]
DATA_FILE = REPO_ROOT / "data" / "io_leaders.yaml"
OUT_FILE = REPO_ROOT / "src" / "in_game" / "common" / "generic_actions" / "tv_io_leader_actions.txt"

HEADER = """\
# @Generated by scripts/in_game/common/generic_actions/gen_tv_io_leader_actions.py
#   Data:    data/io_leaders.yaml
#   Regen:   conda run --no-capture-output -n eu5 python scripts/in_game/common/generic_actions/gen_tv_io_leader_actions.py
# Do not edit directly — modify the data file and re-run the generator.
"""

SECTION_BANNER = """\
# ═════════════════════════════════════════════════════════════════════════════
# {title} (non-unique IO)
# ═════════════════════════════════════════════════════════════════════════════
"""


def _char_selector_block(io: dict) -> str:
    """Return the select_trigger block for Appoint and Change actions."""
    lines = ["\tselect_trigger = {"]
    lines.append("\t\tlooking_for_a = character")
    lines.append("\t\tsource = actor")
    lines.append("\t\ttarget_flag = target")
    lines.append(f'\t\tname = "{io["select_name"]}"')
    lines.append(f'\t\tnone_available_msg_key = "{io["no_leader_msg"]}"')
    lines.append("\t\tcolumn = { data = character_info }")
    lines.append("\t\tvisible = {")
    lines.append("\t\t\tis_alive = yes")
    char_filter = io.get("char_filter", "").strip()
    if char_filter:
        for line in char_filter.splitlines():
            lines.append(f"\t\t\t{line.strip()}")
    lines.append("\t\t\tis_ruler = no")
    lines.append("\t\t\tis_heir = no")
    lines.append("\t\t\tis_consort = no")
    lines.append("\t\t}")
    lines.append("\t}")
    return "\n".join(lines)


def _io_iterator(io_type: str, indent: str) -> list[str]:
    """Return every_international_organizations_member_of block lines (no leader_country check)."""
    t = indent
    return [
        f"{t}every_international_organizations_member_of = {{",
        f"{t}\tlimit = {{",
        f"{t}\t\tinternational_organization_type = international_organization_type:{io_type}",
        f"{t}\t}}",
        f"{t}\tinternational_organization_chooses_new_leader = this",
        f"{t}}}",
    ]


def gen_appoint(io: dict) -> str:
    selector = _char_selector_block(io)
    iterator = "\n".join(_io_iterator(io["io_type"], "\t\t\t\t"))
    return (
        f"tv_appoint_{io['id']}_leader = {{\n"
        f"\ttype = owncountry\n"
        f"\tsound = UI_action_religion_generic\n"
        f"\tai_tick = monthly\n"
        f"\tai_tick_frequency = 99999\n"
        f"\n"
        f"\tpotential = {{\n"
        f"\t\tscope:actor = {{ has_variable = {io['member_var']} }}\n"
        f"\t}}\n"
        f"\n"
        f"\tallow = {{ always = yes }}\n"
        f"\n"
        f"{selector}\n"
        f"\n"
        f"\teffect = {{\n"
        f"\t\tif = {{\n"
        f"\t\t\tlimit = {{ exists = scope:target }}\n"
        f"\t\t\tscope:actor = {{\n"
        f"\t\t\t\tset_variable = {{ name = {io['leader_var']} value = scope:target }}\n"
        f"{iterator}\n"
        f"\t\t\t}}\n"
        f"\t\t}}\n"
        f"\t}}\n"
        f"\n"
        f"\tai_will_do = {{ add = -100 }}\n"
        f"}}\n"
    )


def gen_remove(io: dict) -> str:
    iterator = "\n".join(_io_iterator(io["io_type"], "\t\t\t"))
    return (
        f"tv_remove_{io['id']}_leader = {{\n"
        f"\ttype = owncountry\n"
        f"\tsound = UI_action_religion_generic\n"
        f"\tai_tick = monthly\n"
        f"\tai_tick_frequency = 99999\n"
        f"\n"
        f"\tpotential = {{\n"
        f"\t\tscope:actor = {{ has_variable = {io['member_var']} }}\n"
        f"\t}}\n"
        f"\n"
        f"\tallow = {{ always = yes }}\n"
        f"\n"
        f"\teffect = {{\n"
        f"\t\tscope:actor = {{\n"
        f"\t\t\tremove_variable = {io['leader_var']}\n"
        f"{iterator}\n"
        f"\t\t}}\n"
        f"\t}}\n"
        f"\n"
        f"\tai_will_do = {{ add = -100 }}\n"
        f"}}\n"
    )


def gen_change(io: dict) -> str:
    selector = _char_selector_block(io)
    iterator = "\n".join(_io_iterator(io["io_type"], "\t\t\t\t"))
    return (
        f"tv_change_{io['id']}_leader = {{\n"
        f"\ttype = owncountry\n"
        f"\tsound = UI_action_religion_generic\n"
        f"\tai_tick = monthly\n"
        f"\tai_tick_frequency = 99999\n"
        f"\n"
        f"\tpotential = {{\n"
        f"\t\tscope:actor = {{ has_variable = {io['member_var']} }}\n"
        f"\t}}\n"
        f"\n"
        f"\tallow = {{ always = yes }}\n"
        f"\n"
        f"{selector}\n"
        f"\n"
        f"\teffect = {{\n"
        f"\t\tif = {{\n"
        f"\t\t\tlimit = {{ exists = scope:target }}\n"
        f"\t\t\tscope:actor = {{\n"
        f"\t\t\t\tset_variable = {{ name = {io['leader_var']} value = scope:target }}\n"
        f"{iterator}\n"
        f"\t\t\t}}\n"
        f"\t\t}}\n"
        f"\t}}\n"
        f"\n"
        f"\tai_will_do = {{ add = -100 }}\n"
        f"}}\n"
    )


def _io_title(io: dict) -> str:
    return io.get("display_name", io["id"].replace("_", " ").title())


def generate(data: dict) -> str:
    parts = [HEADER]
    for io in data["ios"]:
        parts.append(SECTION_BANNER.format(title=_io_title(io)))
        parts.append(gen_appoint(io))
        parts.append(gen_remove(io))
        parts.append(gen_change(io))
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry", action="store_true", help="Print to stdout instead of writing")
    args = parser.parse_args()

    with open(DATA_FILE, encoding="utf-8") as f:
        data = yaml.safe_load(f)

    content = generate(data)

    if args.dry:
        print(content)
    else:
        OUT_FILE.write_text(content, encoding="utf-8-sig")
        print(f"Written: {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
