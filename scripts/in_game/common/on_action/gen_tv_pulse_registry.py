ED_ON_ACTION_SUBSTRINGS = ("engineering_department", "wonder")


def _is_ed_on_action(name: str) -> bool:
    lname = name.lower()
    return any(s in lname for s in ED_ON_ACTION_SUBSTRINGS)

HEADER_TEMPLATE = """\
# @Generated by {script}
#   Data:    {data}
#   Regen:   conda run --no-capture-output -n eu5 python {script}
# Do not edit directly — modify the data file and re-run the generator.

"""

def extract_on_action_block(lines: list[str], hook_name: str) -> list[str]:
    """Return only the named on_action block from a multi-action source file."""
    start_idx: int | None = None
    depth = 0

    for i, raw in enumerate(lines):
        stripped = raw.strip()
        if start_idx is None:
            if stripped.startswith(hook_name) and "=" in stripped and "{" in stripped:
                start_idx = i
                depth = stripped.count("{") - stripped.count("}")
                if depth <= 0:
                    return [raw]
            continue

        depth += stripped.count("{") - stripped.count("}")
        if depth <= 0:
            return lines[start_idx:i + 1]

    raise ValueError(f"on_action block not found or unterminated: '{hook_name}'")


def build_bridge_block(hook_name: str, additions: list[str]) -> list[str]:
    """Build a small bridge that registers TV-owned on_actions."""
    lines = [
        f"{hook_name} = {{\n",
        "\ton_actions = {\n",
        "\t\t# Towards Victory additions\n",
    ]
    for name in additions:
        lines.append(f"\t\t{name}\n")
    lines.extend([
        "\t}\n",
        "}\n",
    ])
    return lines


def verify_source(hook_name: str) -> None:
    src_path = SOURCE_FILES[hook_name]

    if src_path is None:
        print(f"Skipping source verification for custom hook: {hook_name}")
    else:
        print(f"Reading source: {src_path.relative_to(REPO_ROOT)}")
        # Use utf-8-sig to strip UTF-8 BOM if present (some vanilla files start with BOM)
        text = src_path.read_text(encoding="utf-8-sig")
        lines = text.splitlines(keepends=True)
        extract_on_action_block(lines, hook_name)


def main() -> None:
    registry = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))
    groups = [
        ("singleton pulse/death bridges", registry.get("pulses", {})),
        ("general/hardcoded hook bridges", registry.get("bridges", {})),
    ]

    blocks: list[str] = []
    ed_blocks: list[str] = []
    for label, hooks in groups:
        group_blocks: list[str] = []
        ed_group_blocks: list[str] = []
        for hook_name, additions in hooks.items():
            if hook_name not in SOURCE_FILES:
                print(f"WARNING: no source mapping for '{hook_name}', skipping")
                continue
            verify_source(hook_name)
            main_additions = [a for a in additions if not _is_ed_on_action(a)]
            ed_additions = [a for a in additions if _is_ed_on_action(a)]
            if main_additions:
                group_blocks.append("".join(build_bridge_block(hook_name, main_additions)).rstrip())
            if ed_additions:
                ed_group_blocks.append("".join(build_bridge_block(hook_name, ed_additions)).rstrip())
        if group_blocks:
            blocks.append(f"# {label}")
            blocks.extend(group_blocks)
        if ed_group_blocks:
            ed_blocks.append(f"# {label}")
            ed_blocks.extend(ed_group_blocks)

    header = HEADER_TEMPLATE.format(script=SCRIPT_REL, data=DATA_REL)
    output = header + "\n\n".join(blocks) + "\n"
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(output, encoding="utf-8-sig")
    print(f"Wrote: {OUTPUT_FILE.relative_to(REPO_ROOT)}")

    ed_output = header + "\n\n".join(ed_blocks) + "\n"
    ED_OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    ED_OUTPUT_FILE.write_text(ed_output, encoding="utf-8-sig")
    print(f"Wrote: {ED_OUTPUT_FILE.relative_to(REPO_ROOT)}")

    print("Done.")


if __name__ == "__main__":
    main()
