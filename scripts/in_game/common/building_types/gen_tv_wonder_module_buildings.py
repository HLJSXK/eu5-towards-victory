import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from wonder_mechanics_lib import PARTS, load_all_wonder_mechanics

OUT_FILE = REPO_ROOT / "src" / "in_game" / "common" / "building_types" / "tv_wonder_module_buildings.txt"
SCRIPT_REL = "scripts/in_game/common/building_types/gen_tv_wonder_module_buildings.py"
DATA_REL = "data/wonders.yaml + data/unique_wonders.yaml"

HEADER = [
    f"# @Generated by {SCRIPT_REL}",
    f"#   Data:    {DATA_REL}",
    f"#   Regen:   conda run --no-capture-output -n eu5 python {SCRIPT_REL}",
    "# Do not edit directly - modify the data file and re-run the generator.",
    "",
]


def building_block(name: str, wonder: dict, modifier_value: float) -> list[str]:
    return [
        f"{name} = {{",
        "\tis_special = yes",
        "\tis_foreign = no",
        f"\tpop_type = {wonder['pop_type']}",
        "\tmax_levels = 6",
        "\temployment_size = 0.1",
        f"\tcategory = {wonder['category']}",
        "",
        "\ttown = yes",
        "\tcity = yes",
        "\tmegalopolis = yes",
        "\trural_settlement = yes",
        "",
        "\timportant_for_AI = no",
        "\tautomation_build_allowed = no",
        "\tcountry_potential = { always = no }",
        "\tallow = {",
        "\t\tcustom_tooltip = {",
        "\t\t\ttext = TV_WONDER_ENGINEERING_ONLY_BUILDING_TT",
        "\t\t\talways = no",
        "\t\t}",
        "\t}",
        "\tcan_destroy = { always = no }",
        "",
        "\tbuild_time = village_build_time",
        "",
        "\tmodifier = {",
        f"\t\tlocal_cultural_tradition = {modifier_value:.1f}",
        "\t}",
        "",
        "\tpossible_production_methods = {",
        f"\t\t{wonder['maintenance']}",
        "\t}",
        "}",
        "",
    ]


def main() -> None:
    wonders, _ = load_all_wonder_mechanics()
    lines = HEADER[:]
    for wonder in wonders:
        for part in PARTS:
            lines.extend(building_block(f"tv_wonder_{wonder['key']}_{part}", wonder, 0.1))
        lines.extend(building_block(f"tv_wonder_{wonder['key']}", wonder, 0.4))
    OUT_FILE.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"Wrote {OUT_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
