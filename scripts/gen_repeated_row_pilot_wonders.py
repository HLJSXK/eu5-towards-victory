def panel_status_key_prefix(name_slug: str) -> str:
    return f"TV_ENGINEERING_{name_slug.upper()}"


def opening_row_set(wonder: dict) -> dict:
    """The row set whose opening stage has the lowest event_id; used for the card title."""
    return min(wonder["row_sets"], key=lambda rs: min(st["event_id"] for st in rs["stages"]))


def build_panel_status_lines(wonder: dict, language: str) -> list[str]:
    name_slug = wonder["name_slug"]
    wonder_key = wonder["wonder_key"]
    key_prefix = panel_status_key_prefix(name_slug)
    lang_index = 0 if language == "english" else 1
    title_field = "en_title" if language == "english" else "zh_title"

    lines: list[str] = []

    opening_rs = opening_row_set(wonder)
    opening_stage = min(opening_rs["stages"], key=lambda st: st["event_id"])
    lines.append(f' {key_prefix}_OPENING_TITLE:0 "{opening_stage[title_field]}"')

    lines.append(f' {key_prefix}_CURRENT_STAGE:0 "{PANEL_CURRENT_STAGE_LABEL[lang_index]}"')
    for row_set in wonder["row_sets"]:
        row_set_key = row_set["row_set_key"]
        label = PANEL_ROW_SET_LABELS[wonder_key][row_set_key][lang_index]
        lines.append(f' {key_prefix}_STAGE_{row_set_key.upper()}:0 "{label}"')
    lines.append(f' {key_prefix}_STAGE_REWARD:0 "{PANEL_STAGE_REWARD_LABEL[lang_index]}"')

    for word_key, values in PANEL_STATUS_WORDS.items():
        lines.append(f' {key_prefix}_STATUS_{word_key.upper()}:0 "{values[lang_index]}"')

    for row_set in wonder["row_sets"]:
        row_set_key = row_set["row_set_key"]
        label = PANEL_ROW_SET_LABELS[wonder_key][row_set_key][lang_index]
        lines.append(f' {key_prefix}_{row_set_key.upper()}_STATUS:0 "{label}"')

    lines.append(f' {key_prefix}_REWARD_BRANCH_STATUS:0 "{PANEL_REWARD_BRANCH_LABEL[lang_index]}"')

    return lines


def build_localization(wonder: dict, language: str) -> str:
    name_slug = wonder["name_slug"]
    header_key = "l_english" if language == "english" else "l_simp_chinese"
    suffix = "l_english" if language == "english" else "l_simp_chinese"
    target = f"src/main_menu/localization/{language}/tv_wonder_unique_{name_slug}_ritual_{suffix}.yml"

    lines = [f"{header_key}:"]
    for hline in header_lines(target):
        lines.append(f" {hline}")
    lines.append(" ")

    all_stages: list[dict] = []
    for row_set in wonder["row_sets"]:
        for stage in row_set["stages"]:
            all_stages.append(stage)
    all_stages.sort(key=lambda st: st["event_id"])

    title_field = "en_title" if language == "english" else "zh_title"
    desc_field = "en_desc" if language == "english" else "zh_desc"
    options_field = "en_options" if language == "english" else "zh_options"

    for stage in all_stages:
        event_id = stage["event_id"]
        lines.append(f' {loc_key(event_id, "t")}:0 "{stage[title_field]}"')
        lines.append(f' {loc_key(event_id, "d")}:0 "{stage[desc_field]}"')
        for option_index, option_text in enumerate(stage[options_field]):
            letter = OPTION_LETTERS[option_index]
            lines.append(f' {loc_key(event_id, letter)}:0 "{option_text}"')

    lines.extend(build_panel_status_lines(wonder, language))

    return "\n".join(lines).rstrip() + "\n"


