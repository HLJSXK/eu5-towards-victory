def header_lines(target: str) -> list[str]:
    return [
        f"# @Generated by {SCRIPT_REL}",
        f"#   Data:    {DATA_REL}",
        f"#   Regen:   conda run --no-capture-output -n eu5 python {SCRIPT_REL}",
        "# Do not edit directly — modify the data file and re-run the generator.",
        f"# Target: {target}",
    ]


def load_data() -> dict:
    with DATA_FILE.open(encoding="utf-8") as f:
        return yaml.safe_load(f)


def row_prefix(name_slug: str, row_set_key: str) -> str:
    return f"tv_wonder_unique_{name_slug}_ritual_{row_set_key}"


def loc_key(event_id: int, suffix: str) -> str:
    return f"{NAMESPACE}.{event_id}.{suffix}"


