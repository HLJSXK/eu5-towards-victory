def output_paths(wonder: dict) -> dict[str, Path]:
    name_slug = wonder["name_slug"]
    return {
        "events": REPO_ROOT / "src" / "in_game" / "events" / f"tv_wonder_unique_{name_slug}_ritual_events.txt",
        "effects": REPO_ROOT / "src" / "in_game" / "common" / "scripted_effects" / f"tv_wonder_unique_{name_slug}_ritual_effects.txt",
        "triggers": REPO_ROOT / "src" / "in_game" / "common" / "scripted_triggers" / f"tv_wonder_unique_{name_slug}_ritual_triggers.txt",
        "l_english": REPO_ROOT / "src" / "main_menu" / "localization" / "english" / f"tv_wonder_unique_{name_slug}_ritual_l_english.yml",
        "l_simp_chinese": REPO_ROOT / "src" / "main_menu" / "localization" / "simp_chinese" / f"tv_wonder_unique_{name_slug}_ritual_l_simp_chinese.yml",
    }


def build_all(wonder: dict) -> dict[str, str]:
    return {
        "events": build_events(wonder),
        "effects": build_effects(wonder),
        "triggers": build_triggers(wonder),
        "l_english": build_localization(wonder, "english"),
        "l_simp_chinese": build_localization(wonder, "simp_chinese"),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Write the generated files (default: dry-run preview).")
    args = parser.parse_args()

    data = load_data()
    wonders = data["wonders"]

    total_events = 0
    for wonder_key, wonder in wonders.items():
        outputs = build_all(wonder)
        paths = output_paths(wonder)
        event_count = sum(len(rs["stages"]) for rs in wonder["row_sets"])
        total_events += event_count
        print(f"{wonder_key} (wonder_id={wonder['wonder_id']}): {event_count} events across {len(wonder['row_sets'])} row set(s)")
        for key, path in paths.items():
            content = outputs[key]
            if args.write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8-sig")
                print(f"  Wrote {path.relative_to(REPO_ROOT)}")
            else:
                print(f"  Dry-run: would write {path.relative_to(REPO_ROOT)} ({len(content.splitlines())} lines)")

    mode = "Wrote" if args.write else "Dry-run"
    print(f"{mode}: {len(wonders)} wonders, {total_events} events, {5 * len(wonders)} files.")


if __name__ == "__main__":
    main()
