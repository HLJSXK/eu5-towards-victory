"""Generate the 3 pilot "Unique Wonder Ritual" wonders using a repeated-row
event/effect/trigger pattern structurally identical to the Alhambra Harness
output (src/in_game/events/tv_wonder_unique_alhambra_ritual_events.txt and its
sibling effects/triggers/localization files), but produced by a small,
project-owned generator instead of the frozen Harness pipeline.

This is deliberately analogous to how Pharos has its own standalone generator
(scripts/in_game/events/gen_tv_wonder_unique_pharos_lighthouse_ritual_events.py)
rather than routing through scripts/gen_unique_wonder_ritual_code.py. It does
NOT read or write anything under the frozen Harness surface: it never touches
scripts/wonder_unique_ritual_harness.py, scripts/gen_unique_wonder_ritual_code.py,
or the identity.status / generation.status / may_write_src fields of
data/unique_wonder_ritual_specs.yaml.

Usage:
    C:\\Users\\Hades\\anaconda3\\envs\\eu5\\python.exe scripts\\gen_repeated_row_pilot_wonders.py          # dry-run, prints a summary
    C:\\Users\\Hades\\anaconda3\\envs\\eu5\\python.exe scripts\\gen_repeated_row_pilot_wonders.py --write  # writes all 15 files

1对1原则: data/repeated_row_pilot_wonders.yaml stores the wonder identity, the
per-row-set stage list, and each stage's fully authored EN/ZH title, desc, and
option text verbatim; this generator is a template filler that arranges that
data into the Alhambra-shaped event/effect/trigger/localization skeleton. It
does not invent or rewrite narrative text.

Generated files (do NOT hand-edit; edit data/repeated_row_pilot_wonders.yaml
and re-run this script instead):
  src/in_game/events/tv_wonder_unique_{name_slug}_ritual_events.txt (x3)
  src/in_game/common/scripted_effects/tv_wonder_unique_{name_slug}_ritual_effects.txt (x3)
  src/in_game/common/scripted_triggers/tv_wonder_unique_{name_slug}_ritual_triggers.txt (x3)
  src/main_menu/localization/english/tv_wonder_unique_{name_slug}_ritual_l_english.yml (x3)
  src/main_menu/localization/simp_chinese/tv_wonder_unique_{name_slug}_ritual_l_simp_chinese.yml (x3)
"""
