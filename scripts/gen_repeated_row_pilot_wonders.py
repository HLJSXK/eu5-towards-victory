def build_effects(wonder: dict) -> str:
    name_slug = wonder["name_slug"]
    lines = header_lines(f"src/in_game/common/scripted_effects/tv_wonder_unique_{name_slug}_ritual_effects.txt")
    prefixes = [row_prefix(name_slug, rs["row_set_key"]) for rs in wonder["row_sets"]]

    for prefix in prefixes:
        lines.append("")
        lines.extend(_row_init_block(prefix))
        lines.append("")
        lines.extend(_row_state_write_block(prefix))
        lines.append("")
        lines.extend(_aggregate_refresh_block(prefix))
        lines.append("")
        lines.extend(_branch_write_block(prefix))
        lines.append("")
        lines.extend(_cleanup_write_block(prefix))

    for prefix in prefixes:
        lines.append("")
        lines.extend(_completion_block(prefix))
        lines.append("")
        lines.extend(_failure_block(prefix))
        lines.append("")
        lines.extend(_ownership_loss_block(prefix))
        lines.append("")
        lines.extend(_ritual_reset_block(prefix))

    return "\n".join(lines).rstrip() + "\n"


