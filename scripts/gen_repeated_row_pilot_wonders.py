def build_events(wonder: dict) -> str:
    name_slug = wonder["name_slug"]
    lines = header_lines(f"src/in_game/events/tv_wonder_unique_{name_slug}_ritual_events.txt")
    lines.append(f"namespace = {NAMESPACE}")
    lines.append("")

    all_stages: list[tuple[str, dict]] = []
    for row_set in wonder["row_sets"]:
        for stage in row_set["stages"]:
            all_stages.append((row_set["row_set_key"], stage))
    all_stages.sort(key=lambda item: item[1]["event_id"])

    for row_set_key, stage in all_stages:
        prefix = row_prefix(name_slug, row_set_key)
        event_id = stage["event_id"]
        stage_name = stage["stage"]
        option_count = len(stage["en_options"])

        lines.append(f"# -- {NAMESPACE}.{event_id} {DASH_RULE}")
        lines.append(f"{NAMESPACE}.{event_id} = {{")
        lines.append(f"{T}type = country_event")
        lines.append(f"{T}title = {NAMESPACE}.{event_id}.t")
        lines.append(f"{T}desc = {NAMESPACE}.{event_id}.d")
        lines.append(f"{T}outcome = neutral")
        lines.append("")
        lines.append(f"{T}# row_set = {row_set_key}; stage = {stage_name}")
        lines.append("")

        for option_index in range(option_count):
            letter = OPTION_LETTERS[option_index]
            lines.append(f"{T}option = {{")
            lines.append(f"{T}{T}name = {NAMESPACE}.{event_id}.{letter}")
            lines.append(f"{T}{T}trigger = {{")
            lines.append(f"{T}{T}{T}{prefix}_scripted_trigger_eligibility_trigger = yes")
            lines.append(f"{T}{T}{T}{prefix}_scripted_trigger_tooltip_safe_condition_group_trigger = yes")
            lines.append(f"{T}{T}}}")
            if stage_name == "opening":
                lines.append(f"{T}{T}{prefix}_row_init_effect = yes")
                lines.append(f"{T}{T}{prefix}_aggregate_refresh_effect = yes")
            elif stage_name == "update":
                lines.append(f"{T}{T}{prefix}_row_state_write_effect = yes")
                lines.append(f"{T}{T}{prefix}_aggregate_refresh_effect = yes")
            elif stage_name == "retry":
                lines.append(f"{T}{T}{prefix}_branch_write_effect = yes")
                lines.append(f"{T}{T}{prefix}_aggregate_refresh_effect = yes")
            elif stage_name == "resolve":
                lines.append(f"{T}{T}{prefix}_completion_effect = yes")
                lines.append(f"{T}{T}{prefix}_cleanup_write_effect = yes")
            else:
                raise ValueError(f"Unknown stage {stage_name!r} for {name_slug}/{row_set_key}")
            lines.append(f"{T}}}")
            lines.append("")

        # drop the trailing blank line inserted after the last option, then close event
        if lines[-1] == "":
            lines.pop()
        lines.append("}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


