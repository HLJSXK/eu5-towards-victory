def _row_init_block(prefix: str) -> list[str]:
    lines = [f"# -- {prefix}_row_init_effect {DASH_RULE}", f"{prefix}_row_init_effect = {{"]
    lines.append(f"{T}# family = effect; operation = row_init")
    lines.append(f"{T}# row_set = {prefix.split('_ritual_', 1)[1]}")
    for suffix, value in (
        ("started", 1),
        ("progress", 0),
        ("branch", 0),
        ("completed", 0),
        ("failed", 0),
        ("reset", 0),
        ("state", 0),
    ):
        lines.append(f"{T}set_variable = {{ name = {prefix}_{suffix} value = {value} }}")
    lines.append("}")
    return lines


