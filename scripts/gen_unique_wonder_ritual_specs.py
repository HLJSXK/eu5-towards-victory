#!/usr/bin/env python3
"""Scaffold or refresh the unique wonder ritual Harness spec source."""

import argparse
import sys

from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from wonder_mechanics.io import dump_yaml_document  # noqa: E402
from wonder_unique_ritual_harness import (  # noqa: E402
    SPEC_FILE,
    append_missing_design_placeholders,
    build_spec_payload,
    load_spec_data,
    validate_spec_payload,
)

GENERATED_HEADER = """# @Generated by scripts/gen_unique_wonder_ritual_specs.py
#   Data:    data/unique_wonders.yaml + data/unique_wonder_ritual_designs.yaml + data/unique_wonder_ritual_prompts.yaml + data/wonder_localization.yaml
#   Regen:   conda run --no-capture-output -n eu5 python scripts/gen_unique_wonder_ritual_specs.py
# Do not edit directly - modify the source data and re-run the generator.

"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Validate the generated scaffold in memory without writing it.",
    )
    parser.add_argument(
        "--preserve-existing",
        action="store_true",
        default=True,
        help="Preserve existing authored spec entries and only add missing entries.",
    )
    parser.add_argument(
        "--sync-design-placeholders",
        action="store_true",
        help="Append needs_design placeholders for unique wonders missing from data/unique_wonder_ritual_designs.yaml.",
    )
    args = parser.parse_args()

    if args.sync_design_placeholders:
        added = append_missing_design_placeholders()
        if added:
            print(f"Appended {len(added)} design placeholder(s): {', '.join(added)}")
        else:
            print("No missing design placeholders.")

    existing = load_spec_data() if SPEC_FILE.exists() and args.preserve_existing else None
    payload = build_spec_payload(existing)
    errors = validate_spec_payload(payload)
    if errors:
        print("[FAIL] Generated unique ritual spec scaffold failed validation:")
        for error in errors:
            print(f"  - {error}")
        sys.exit(1)

    text = GENERATED_HEADER + dump_yaml_document(payload)
    if args.check:
        print("[OK] Unique ritual spec scaffold validates in memory.")
        return

    SPEC_FILE.write_text(text, encoding="utf-8")
    print(f"Wrote {SPEC_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
