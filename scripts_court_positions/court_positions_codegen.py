def load_positions() -> list[dict]:
    with DATA_FILE.open(encoding="utf-8-sig") as file:
        data = yaml.safe_load(file)
    positions = data.get("positions", [])
    if not positions:
        raise ValueError("Court Positions must define at least one position")
    ids = [position["id"] for position in positions]
    if len(set(ids)) != len(ids):
        raise ValueError("Court position ids must be unique")
    for position in positions:
        if position["ability"] not in ABILITY_IDS:
            raise ValueError(f"Unsupported ability for {position['id']}")
        for key in ("name_en", "name_zh", "icon", "description_en", "description_zh", "effect_en", "effect_zh"):
            if not position.get(key):
                raise ValueError(f"Court position {position['id']} is missing {key}")
    return positions


