        f"\t\t\tscope:{holder_scope} = {{\n"
        "\t\t\t\tadd_character_modifier = { modifier = busy_modifier years = -1 mode = add_and_extend }\n"
        "\t\t\t}\n"
        f"\t\t\tscope:{country_scope} = {{\n"
        f"\t\t\t\tset_variable = {{ name = {ability_var(position)}\n{ability_block}\n\t\t\t\t}}\n"
        f"\t\t\t\tclamp_variable = {{ name = {ability_var(position)} min = 0 max = 100 }}\n"
        f"\t\t\t\tset_variable = {{\n"
