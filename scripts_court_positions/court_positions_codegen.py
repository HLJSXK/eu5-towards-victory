def render_gui(positions: Iterable[dict], script_rel: str) -> str:
    positions = list(positions)
    lines: list[str] = []
    emit(lines, 0, "situation_panel = {")
    emit(lines, 1, "# The vanilla situation panel owns the header, tabs, and scroll area.")
    emit(lines, 1, "# Situation-specific cards must be injected into this named content block.")
    emit(lines, 1, 'blockoverride "situation_panel_main_content" {')
    emit(lines, 2, "vbox = {")
    grid_width = CARD_COLUMNS * CARD_WIDTH + (CARD_COLUMNS - 1) * CARD_SPACING
    emit(lines, 3, "layoutpolicy_horizontal = fixed")
    emit(lines, 3, f"minimumsize = {{ {grid_width} -1 }}")
    emit(lines, 3, f"maximumsize = {{ {grid_width} -1 }}")
    emit(lines, 3, f"spacing = {CARD_SPACING}")
    emit(lines, 3, f"margin = {{ {GRID_MARGIN} {GRID_MARGIN} }}")
    for start in range(0, len(positions), CARD_COLUMNS):
        row = positions[start:start + CARD_COLUMNS]
        emit(lines, 3, "hbox = {")
        emit(lines, 4, "layoutpolicy_horizontal = fixed")
        emit(lines, 4, f"spacing = {CARD_SPACING}")
        for offset, position in enumerate(row):
            _append_gui_card(lines, 4, position, start + offset)
        for _ in range(CARD_COLUMNS - len(row)):
            emit(lines, 4, f"widget = {{ size = {{ {CARD_WIDTH} {CARD_HEIGHT} }} }}")
        emit(lines, 3, "}")
    emit(lines, 2, "}")
    emit(lines, 1, "}")
    emit(lines, 0, "}")
    return header(script_rel) + "\n".join(lines) + "\n"


