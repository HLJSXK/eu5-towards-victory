def render_localization(positions: Iterable[dict], script_rel: str, language: str) -> bytes:
    zh = language == "simp_chinese"
    header_key = "l_simp_chinese" if zh else "l_english"
    entries: list[tuple[str, str]] = [
        ("TV_COURT_POSITIONS_TITLE", "宫廷职位" if zh else "Court Positions"),
        ("TV_COURT_POSITIONS_INTRO", "左键卡片可任命或更换职位；右键卡片可解任。职位效果与薪水均随人物能力线性变化。" if zh else "Left-click a card to appoint or replace its holder; right-click to dismiss. Effects and salaries scale linearly with the holder's ability."),
        ("TV_COURT_POSITION_VACANT", "职位空缺" if zh else "Vacant Position"),
        ("TV_COURT_ABILITY_LABEL", "能力：" if zh else "Ability:"),
        ("TV_COURT_SALARY_LABEL", "月薪：" if zh else "Monthly Salary:"),
        ("TV_COURT_SALARY_FORMULA", "月薪 = 能力 / 100 × (1 + [economical_base|e] × 0.1)。" if zh else "Monthly salary = Ability / 100 × (1 + [economical_base|e] × 0.1)."),
    ]
    for position in positions:
        prefix = f"TV_COURT_{position['id'].upper()}"
        entries.extend([
            (f"{prefix}_TITLE", position["name_zh"] if zh else position["name_en"]),
            (f"STATIC_MODIFIER_NAME_{effect_modifier(position)}", position["name_zh"] if zh else position["name_en"]),
        ])
        for ability in range(101):
            entries.append((f"STATIC_MODIFIER_NAME_{display_modifier(position, ability)}", position["name_zh"] if zh else position["name_en"]))
        entries.extend(_action_localization_entries(position, language))
        for action in (appointment_action(position), dismissal_action(position)):
            entries.extend(_message_localization_entries(action, language))
    lines = [
        f"{header_key}:",
        f"# @Generated by {script_rel}",
        f"#   Data:    {DATA_REL}",
        f"#   Regen:   conda run --no-capture-output -n eu5 python {script_rel}",
        "# Do not edit directly — modify the data file and re-run the generator.",
        "",
    ]
    for key, value in entries:
        lines.append(f' {key}: "{value.replace(chr(34), chr(92) + chr(34))}"')
    return b"\xef\xbb\xbf" + ("\n".join(lines) + "\n").encode("utf-8")
