def render_scripted_effects(positions: Iterable[dict], script_rel: str) -> str:
    positions = list(positions)
    blocks: list[str] = []
    blocks.extend(_render_remove_effect(position) for position in positions)
    blocks.extend(_render_refresh_effect(position) for position in positions)
    blocks.extend(_render_appoint_effect(position) for position in positions)
    blocks.extend(_render_direct_appoint_effect(position) for position in positions)
    lines = [
        "tv_court_positions_refresh_all_effect = {",
        *[f"\ttv_court_positions_refresh_{position['id']}_effect = yes" for position in positions],
        "}",
        "",
        "tv_court_positions_initialize_country_effect = {",
        "\tset_variable = { name = tv_court_positions_initialized value = 1 }",
        *[f"\tif = {{ limit = {{ NOT = {{ has_variable = {ability_var(position)} }} }} set_variable = {{ name = {ability_var(position)} value = 0 }} }}" for position in positions],
        *[f"\tif = {{ limit = {{ NOT = {{ has_variable = {salary_var(position)} }} }} set_variable = {{ name = {salary_var(position)} value = 0 }} }}" for position in positions],
        "\ttv_court_positions_refresh_all_effect = yes",
        "}",
        "",
        "tv_court_positions_monthly_effect = {",
        "\ttv_court_positions_refresh_all_effect = yes",
    ]
    for position in positions:
        lines.extend([
            "\tif = {",
            f"\t\tlimit = {{ has_variable = {char_var(position)} }}",
            f"\t\tadd_gold = {{ value = var:{salary_var(position)} multiply = -1 }}",
            "\t}",
        ])
    lines.append("}")
    blocks.append("\n".join(lines))
    # Static, unreachable references retain every dynamic ShowModifierEffect target
    # in script scans as well as in the generated static-modifier file.
    ref_lines = ["tv_court_positions_display_modifier_static_reference_effect = {", "\tif = {", "\t\tlimit = { always = no }"]
    for position in positions:
        for ability in range(101):
            ref_lines.append(f"\t\tadd_country_modifier = {{ modifier = {display_modifier(position, ability)} days = 1 }}")
    ref_lines.extend(["\t}", "}"])
    blocks.append("\n".join(ref_lines))
    return header(script_rel) + "\n\n".join(blocks) + "\n"


